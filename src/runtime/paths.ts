import { realpath, stat, mkdir, rename, rm, writeFile, lstat } from 'node:fs/promises';
import { dirname, isAbsolute, relative, resolve } from 'node:path';
import { randomUUID } from 'node:crypto';
import { assertThat, BacktestError } from '../spec/errors.js';

export async function directory(path: string): Promise<string> {
  await mkdir(resolve(path), { recursive: true });
  const canonical = await realpath(path);
  assertThat((await stat(canonical)).isDirectory(), 'INVALID_DIRECTORY', 'Expected a directory');
  return canonical;
}

export async function ownedDirectory(root: string, path: string): Promise<string> {
  assertThat(within(root, resolve(path)), 'PATH_NOT_AUTHORIZED', 'Store directory is outside its root');
  await mkdir(path, { recursive: true });
  const info = await lstat(path), canonical = await realpath(path);
  assertThat(info.isDirectory() && !info.isSymbolicLink() && within(root, canonical), 'PATH_NOT_AUTHORIZED', 'Store directories cannot be symlink escapes');
  return canonical;
}

export function within(root: string, candidate: string): boolean {
  const rel = relative(root, candidate);
  return rel === '' || (!isAbsolute(rel) && rel !== '..' && !rel.startsWith(`..${process.platform === 'win32' ? '\\' : '/'}`));
}

/** Resolve to the actual authorized file, not just a lexical path prefix. */
export async function workspaceFile(workspace: string, path: string): Promise<string> {
  assertThat(typeof path === 'string' && path.length > 0 && !path.includes('\0') && !/^[a-z][a-z\d+.-]*:\/\//i.test(path), 'INVALID_DATA_PATH', 'Expected a local file path', '/path');
  let canonical: string;
  try { canonical = await realpath(resolve(workspace, path)); }
  catch { throw new BacktestError('FILE_NOT_FOUND', 'Input file does not exist', '/path'); }
  assertThat(within(workspace, canonical), 'PATH_NOT_AUTHORIZED', 'Input resolves outside the authorized workspace', '/path');
  assertThat((await stat(canonical)).isFile(), 'INVALID_DATA_PATH', 'Input must be a regular file', '/path');
  return canonical;
}

export function handlePath(root: string, group: string, id: string, prefix: string): string {
  assertThat(typeof id === 'string' && new RegExp(`^${prefix}_[a-zA-Z0-9_-]{1,80}$`).test(id), 'INVALID_HANDLE', `Invalid ${prefix} handle`);
  return resolve(root, group, `${id}.json`);
}

/** Store paths are generated by the service; refuse symlinked files/directories. */
export async function storeFile(root: string, path: string): Promise<string> {
  assertThat(within(root, resolve(path)), 'PATH_NOT_AUTHORIZED', 'Artifact is outside the configured store');
  const info = await lstat(path);
  assertThat(info.isFile() && !info.isSymbolicLink(), 'PATH_NOT_AUTHORIZED', 'Artifact must be an owned regular file');
  const canonical = await realpath(path);
  assertThat(within(root, canonical), 'PATH_NOT_AUTHORIZED', 'Artifact resolves outside the configured store');
  return canonical;
}

export async function atomicJSON(path: string, value: unknown): Promise<void> {
  await mkdir(dirname(path), { recursive: true });
  const temporary = `${path}.${randomUUID()}.tmp`;
  try { await writeFile(temporary, JSON.stringify(value), { flag: 'wx', mode: 0o600 }); await rename(temporary, path); }
  finally { await rm(temporary, { force: true }); }
}
